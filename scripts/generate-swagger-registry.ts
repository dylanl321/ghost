import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, relative, resolve, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const apiDirectory = resolve(projectRoot, 'server/api')
const outputFile = resolve(projectRoot, 'server/generated/swagger-routes.ts')

async function findTypeScriptFiles(directory: string): Promise<string[]> {
  const entries = await readdir(directory, { withFileTypes: true })
  const files = await Promise.all(entries.map(entry => {
    const path = resolve(directory, entry.name)
    return entry.isDirectory() ? findTypeScriptFiles(path) : [path]
  }))
  return files.flat().filter(path => path.endsWith('.ts'))
}

const documentedRoutes: string[] = []
for (const file of await findTypeScriptFiles(apiDirectory)) {
  const source = await readFile(file, 'utf8')
  // Routes register documentation either directly or through the supported v1 alias helper.
  if (source.includes('registerEndpoint') || source.includes('defineV1Alias')) {
    const importPath = `../api/${relative(apiDirectory, file)
      .split(sep).join('/')
      .replace(/\.ts$/, '')}`
    documentedRoutes.push(importPath)
  }
}
documentedRoutes.sort((left, right) => left.localeCompare(right))

const generatedSource = `// Generated by scripts/generate-swagger-registry.ts. Do not edit manually.
const documentedRouteLoaders = [
${documentedRoutes.map(path => `  () => import('${path}'),`).join('\n')}
]

export const documentedRouteCount = documentedRouteLoaders.length

export async function loadDocumentedRoutes(): Promise<void> {
  await Promise.all(documentedRouteLoaders.map(loadRoute => loadRoute()))
}
`

await mkdir(dirname(outputFile), { recursive: true })
await writeFile(outputFile, generatedSource)
process.stdout.write(`Generated Swagger registry for ${documentedRoutes.length} route modules\n`)
