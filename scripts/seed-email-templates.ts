async function seedTemplates() {
  console.log('📧 Seeding email templates to DynamoDB...')
  console.log(`   Table: ${TABLE_NAME}`)
  console.log(`   Environment: ${ENVIRONMENT}`)
  console.log('')

  let successCount = 0
  let errorCount = 0

  for (const template of DEFAULT_TEMPLATES) {
    try {
      await putItem(TABLE_NAME, template, ENVIRONMENT)
      console.log(`✅ Created template: ${template.templateName}`)
      successCount++
    } catch (error: any) {
      console.error(`❌ Failed to create ${template.templateName}:`, error.message)
      errorCount++
    }
  }

  console.log('')
  console.log(`✅ Seeding complete: ${successCount} created, ${errorCount} failed`)

  if (errorCount > 0) {
    process.exit(1)
  }
}

// Run if called directly (ESM-compatible check for both Windows and Linux)
import { fileURLToPath } from 'node:url'
const isMainModule = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]
if (isMainModule) {
  seedTemplates().catch((error) => {
    console.error('Fatal error:', error)
    process.exit(1)
  })
}

export { seedTemplates }
