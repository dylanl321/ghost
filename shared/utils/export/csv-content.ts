/**
 * CSV Content Builder
 * Builds CSV text from DataExportConfig; shared by the browser exporter and
 * server-generated scheduled reports
 */

import type { DataExportConfig, SheetConfig } from '#shared/types/export'
import { formatCellValue, escapeCSV, normalizeSheetData } from './format'

/**
 * Generate CSV content from a single sheet
 */
export function generateCSVContent(
  sheet: SheetConfig,
  config: DataExportConfig
): string {
  const { headers, rows } = normalizeSheetData(sheet.data, sheet.columns)

  const csvLines: string[] = []

  // Add sheet description if present
  if (sheet.description) {
    csvLines.push(`# ${sheet.description}`)
    csvLines.push('')
  }

  // Add metadata section if requested
  if (config.options?.includeMetadata !== false && config.metadata) {
    csvLines.push('# Metadata')
    if (config.metadata.generatedBy) {
      csvLines.push(`Generated By,${escapeCSV(config.metadata.generatedBy)}`)
    }
    if (config.metadata.timestamp) {
      csvLines.push(`Timestamp,${escapeCSV(config.metadata.timestamp)}`)
    }
    if (config.metadata.timeframe) {
      csvLines.push(`Timeframe,${escapeCSV(config.metadata.timeframe)}`)
    }
    if (config.metadata.mode) {
      csvLines.push(`Mode,${escapeCSV(config.metadata.mode)}`)
    }
    if (config.metadata.scope) {
      csvLines.push(`Scope,${escapeCSV(config.metadata.scope)}`)
    }
    if (config.metadata.selectedAccounts && config.metadata.selectedAccounts.length > 0) {
      csvLines.push(`Selected Accounts,${config.metadata.selectedAccountsCount || config.metadata.selectedAccounts.length}`)
    }
    csvLines.push('')
  }

  // Add headers
  const headerRow = headers.map(header => escapeCSV(header)).join(',')
  csvLines.push(headerRow)

  // Add data rows
  rows.forEach(row => {
    const formattedRow = row.map((cell, index) => {
      const column = sheet.columns?.[index]
      const formatted = formatCellValue(cell, column, sheet.formatting)
      return escapeCSV(formatted)
    })
    csvLines.push(formattedRow.join(','))
  })

  return csvLines.join('\n')
}

/**
 * Concatenate every sheet into one CSV, separated by commented sheet headers
 */
export function buildCombinedCSV(config: DataExportConfig): string {
  const allContent: string[] = []

  allContent.push(`# ${config.title}`)
  if (config.subtitle) {
    allContent.push(`# ${config.subtitle}`)
  }
  allContent.push('')

  config.sheets.forEach((sheet, index) => {
    if (index > 0) {
      allContent.push('')
      allContent.push('---')
      allContent.push('')
    }

    allContent.push(`# Sheet: ${sheet.name}`)
    allContent.push('')
    allContent.push(generateCSVContent(sheet, config))
  })

  return allContent.join('\n')
}
