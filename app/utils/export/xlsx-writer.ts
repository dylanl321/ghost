/**
 * XLSX Writer
 * Generates Excel files from DataExportConfig
 */

import * as XLSX from 'xlsx'
import type { DataExportConfig, ExportResult, SheetConfig } from '~/shared/types/export'
import {
  formatCellValue,
  normalizeSheetData,
  generateFilename,
  downloadBlob,
  calculateColumnWidths
} from './export-utils'

const logger = createLogger('XlsxWriter')

/**
 * Create an Excel workbook from DataExportConfig
 */
export function createWorkbook(config: DataExportConfig): XLSX.WorkBook {
  const workbook = XLSX.utils.book_new()

  // Add metadata sheet if requested
  if (config.options?.includeMetadata !== false && config.metadata) {
    const metadataSheet = createMetadataSheet(config)
    XLSX.utils.book_append_sheet(workbook, metadataSheet, 'Metadata')
  }

  // Add data sheets
  config.sheets.forEach((sheet) => {
    const worksheet = createWorksheet(sheet, config)

    // Sanitize sheet name (Excel has restrictions)
    const sheetName = sanitizeSheetName(sheet.name)

    XLSX.utils.book_append_sheet(workbook, worksheet, sheetName)
  })

  return workbook
}

/**
 * Create metadata sheet
 */
function createMetadataSheet(config: DataExportConfig): XLSX.WorkSheet {
  const metadata = config.metadata
  const data: any[][] = [
    ['Report Title', config.title],
    ...(config.subtitle ? [['Subtitle', config.subtitle]] : []),
    [''],
    ['Metadata', ''],
    ...(metadata.generatedBy ? [['Generated By', metadata.generatedBy]] : []),
    ...(metadata.timestamp ? [['Timestamp', metadata.timestamp]] : []),
    ...(metadata.timeframe ? [['Timeframe', metadata.timeframe]] : []),
    ...(metadata.mode ? [['Mode', metadata.mode]] : []),
    ...(metadata.scope ? [['Scope', metadata.scope]] : []),
    ...(metadata.selectedAccountsCount ? [['Selected Accounts', metadata.selectedAccountsCount]] : [])
  ]

  // Add filters if present
  if (metadata.filters && Object.keys(metadata.filters).length > 0) {
    data.push([''], ['Filters', ''])
    Object.entries(metadata.filters).forEach(([key, value]) => {
      data.push([key, String(value)])
    })
  }

  const worksheet = XLSX.utils.aoa_to_sheet(data)

  // Apply basic styling
  const range = XLSX.utils.decode_range(worksheet['!ref'] || 'A1')

  // Make headers bold (first column)
  for (let row = range.s.r; row <= range.e.r; row++) {
    const cellRef = XLSX.utils.encode_cell({ r: row, c: 0 })
    if (worksheet[cellRef]) {
      worksheet[cellRef].s = {
        font: { bold: true }
      }
    }
  }

  // Set column widths
  worksheet['!cols'] = [
    { wch: 25 },
    { wch: 50 }
  ]

  return worksheet
}

/**
 * Create worksheet from sheet config
 */
function createWorksheet(sheet: SheetConfig, config: DataExportConfig): XLSX.WorkSheet {
  const { headers, rows } = normalizeSheetData(sheet.data, sheet.columns)

  // Format cell values based on column config
  const formattedRows = rows.map(row =>
    row.map((cell, index) => {
      const column = sheet.columns?.[index]
      return formatCellValue(cell, column, sheet.formatting)
    })
  )

  // Create worksheet with headers and data
  const data = [headers, ...formattedRows]
  const worksheet = XLSX.utils.aoa_to_sheet(data)

  // Apply styling
  applyWorksheetStyling(worksheet, sheet, config)

  // Set column widths
  if (config.options?.xlsx?.autoWidth !== false) {
    const widths = calculateColumnWidths(headers, formattedRows)
    worksheet['!cols'] = widths.map(w => ({ wch: w + 2 })) // Add padding
  } else if (sheet.columns) {
    worksheet['!cols'] = sheet.columns.map(col => ({
      wch: col.width || 15
    }))
  }

  // Freeze header row if requested
  if (config.options?.xlsx?.freezeHeader !== false) {
    worksheet['!freeze'] = { xSplit: 0, ySplit: 1 }
  }

  return worksheet
}

/**
 * Apply styling to worksheet
 */
function applyWorksheetStyling(
  worksheet: XLSX.WorkSheet,
  sheet: SheetConfig,
  config: DataExportConfig
): void {
  const range = XLSX.utils.decode_range(worksheet['!ref'] || 'A1')

  // Style header row
  const headerStyle = sheet.formatting?.headerStyle
  if (headerStyle) {
    for (let col = range.s.c; col <= range.e.c; col++) {
      const cellRef = XLSX.utils.encode_cell({ r: 0, c: col })
      if (worksheet[cellRef]) {
        worksheet[cellRef].s = {
          font: {
            bold: headerStyle.bold !== false,
            sz: headerStyle.fontSize || 12,
            color: { rgb: headerStyle.textColor?.replace('#', '') || '000000' }
          },
          fill: {
            fgColor: { rgb: headerStyle.backgroundColor?.replace('#', '') || 'E5E7EB' }
          },
          alignment: { horizontal: 'center', vertical: 'center' }
        }
      }
    }
  }

  // Style data rows
  const rowStyle = sheet.formatting?.rowStyle
  if (rowStyle?.alternateColors) {
    for (let row = range.s.r + 1; row <= range.e.r; row++) {
      const isEvenRow = row % 2 === 0
      const fillColor = isEvenRow ? rowStyle.evenRowColor : rowStyle.oddRowColor

      if (fillColor) {
        for (let col = range.s.c; col <= range.e.c; col++) {
          const cellRef = XLSX.utils.encode_cell({ r: row, c: col })
          if (worksheet[cellRef]) {
            worksheet[cellRef].s = {
              ...worksheet[cellRef].s,
              fill: {
                fgColor: { rgb: fillColor.replace('#', '') }
              }
            }
          }
        }
      }
    }
  }

  // Apply column-specific formatting
  if (sheet.columns) {
    sheet.columns.forEach((column, colIndex) => {
      for (let row = range.s.r + 1; row <= range.e.r; row++) {
        const cellRef = XLSX.utils.encode_cell({ r: row, c: colIndex })
        if (worksheet[cellRef]) {
          // Apply alignment
          if (column.alignment) {
            worksheet[cellRef].s = {
              ...worksheet[cellRef].s,
              alignment: {
                horizontal: column.alignment
              }
            }
          }

          // Apply number formatting
          if (column.format === 'currency') {
            worksheet[cellRef].z = '$#,##0.00'
          } else if (column.format === 'percentage') {
            worksheet[cellRef].z = '0.00%'
          } else if (column.format === 'number') {
            const decimals = column.decimals ?? 2
            worksheet[cellRef].z = decimals > 0 ? `#,##0.${'0'.repeat(decimals)}` : '#,##0'
          } else if (column.format === 'date') {
            worksheet[cellRef].z = 'mmm d, yyyy'
          } else if (column.format === 'datetime') {
            worksheet[cellRef].z = 'mmm d, yyyy h:mm AM/PM'
          }
        }
      }
    })
  }

  // Show gridlines based on option
  if (config.options?.xlsx?.showGridlines === false) {
    worksheet['!views'] = [{ showGridLines: false }]
  }
}

/**
 * Sanitize sheet name for Excel compatibility
 * Excel sheet names cannot exceed 31 characters and cannot contain: \ / ? * [ ]
 */
function sanitizeSheetName(name: string): string {
  return name
    .replace(/[\\/?*[\]]/g, '')
    .substring(0, 31)
}

/**
 * Export data as XLSX
 */
export async function exportToXLSX(
  config: DataExportConfig
): Promise<ExportResult> {
  try {
    const workbook = createWorkbook(config)

    // Generate binary string
    const wbout = XLSX.write(workbook, {
      bookType: 'xlsx',
      type: 'array',
      cellStyles: true
    })

    const blob = new Blob([wbout], {
      type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet'
    })

    const filename = generateFilename(
      config.options?.filename || config.title,
      'xlsx'
    )

    return {
      success: true,
      format: 'xlsx',
      filename,
      blob
    }

  } catch (error) {
    logger.error('XLSX export failed:', error)
    return {
      success: false,
      format: 'xlsx',
      filename: '',
      error: error instanceof Error ? error.message : 'Unknown error during XLSX export'
    }
  }
}

/**
 * Download XLSX file
 */
export function downloadXLSX(result: ExportResult): void {
  if (!result.success || !result.blob) {
    logger.error('Cannot download XLSX:', result.error)
    return
  }

  downloadBlob(result.blob, result.filename)
}
