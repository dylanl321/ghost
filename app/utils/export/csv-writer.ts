/**
 * CSV Writer
 * Generates CSV files from DataExportConfig
 */

import type { DataExportConfig, ExportResult } from '#shared/types/export'
import { generateCSVContent, buildCombinedCSV } from '#shared/utils/export/csv-content'
import {
  generateFilename,
  downloadBlob
} from './export-utils'
import JSZip from 'jszip'

const logger = createLogger('CsvWriter')

/**
 * Export data as CSV
 * If multiple sheets, creates a ZIP file with multiple CSVs
 */
export async function exportToCSV(
  config: DataExportConfig
): Promise<ExportResult> {
  try {
    const multiFileZip = config.options?.csv?.multiFileZip && config.sheets.length > 1

    // Single sheet export
    if (config.sheets.length === 1 && !multiFileZip) {
      const sheet = config.sheets[0]
      const csvContent = generateCSVContent(sheet, config)

      const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' })
      const filename = generateFilename(
        config.options?.filename || config.title,
        'csv'
      )

      return {
        success: true,
        format: 'csv',
        filename,
        blob
      }
    }

    // Multiple sheets export as ZIP
    if (multiFileZip) {
      const zip = new JSZip()

      // Add each sheet as a separate CSV file
      config.sheets.forEach((sheet, index) => {
        const csvContent = generateCSVContent(sheet, config)
        const sheetFilename = `${sheet.name || `Sheet_${index + 1}`}.csv`
        zip.file(sheetFilename, csvContent)
      })

      // Add a README if metadata exists
      if (config.metadata) {
        const readme: string[] = []
        readme.push(`# ${config.title}`)
        if (config.subtitle) {
          readme.push(`${config.subtitle}`)
        }
        readme.push('')
        readme.push('## Export Information')
        if (config.metadata.generatedBy) {
          readme.push(`Generated By: ${config.metadata.generatedBy}`)
        }
        if (config.metadata.timestamp) {
          readme.push(`Timestamp: ${config.metadata.timestamp}`)
        }
        if (config.metadata.timeframe) {
          readme.push(`Timeframe: ${config.metadata.timeframe}`)
        }
        if (config.metadata.mode) {
          readme.push(`Mode: ${config.metadata.mode}`)
        }
        readme.push('')
        readme.push('## Files Included')
        config.sheets.forEach((sheet, index) => {
          readme.push(`- ${sheet.name || `Sheet_${index + 1}`}.csv${sheet.description ? ` - ${sheet.description}` : ''}`)
        })

        zip.file('README.txt', readme.join('\n'))
      }

      // Generate ZIP blob
      const zipBlob = await zip.generateAsync({ type: 'blob' })
      const filename = generateFilename(
        config.options?.filename || config.title,
        'zip'
      )

      return {
        success: true,
        format: 'csv',
        filename,
        blob: zipBlob
      }
    }

    // Fallback: concatenate all sheets into a single CSV with separators
    const blob = new Blob([buildCombinedCSV(config)], { type: 'text/csv;charset=utf-8;' })
    const filename = generateFilename(
      config.options?.filename || config.title,
      'csv'
    )

    return {
      success: true,
      format: 'csv',
      filename,
      blob
    }

  } catch (error) {
    logger.error('CSV export failed:', error)
    return {
      success: false,
      format: 'csv',
      filename: '',
      error: error instanceof Error ? (error instanceof Error ? error.message : String(error)) : 'Unknown error during CSV export'
    }
  }
}

/**
 * Download CSV file
 */
export function downloadCSV(result: ExportResult): void {
  if (!result.success || !result.blob) {
    logger.error('Cannot download CSV:', result.error)
    return
  }

  downloadBlob(result.blob, result.filename)
}
