/**
 * CSV Writer
 * Generates CSV files from DataExportConfig
 */

import type { DataExportConfig, ExportResult, SheetConfig } from '~/shared/types/export'
import {
  formatCellValue,
  escapeCSV,
  normalizeSheetData,
  generateFilename,
  downloadBlob
} from './export-utils'
import JSZip from 'jszip'

/**
 * Generate CSV content from a single sheet
 */
export function generateCSVContent(
  sheet: SheetConfig,
  config: DataExportConfig
): string {
  const { headers, rows } = normalizeSheetData(sheet.data, sheet.columns)

  const csvLines: string[] = []

  // Add sheet description if present
  if (sheet.description) {
    csvLines.push(`# ${sheet.description}`)
    csvLines.push('')
  }

  // Add metadata section if requested
  if (config.options?.includeMetadata !== false && config.metadata) {
    csvLines.push('# Metadata')
    if (config.metadata.generatedBy) {
      csvLines.push(`Generated By,${escapeCSV(config.metadata.generatedBy)}`)
    }
    if (config.metadata.timestamp) {
      csvLines.push(`Timestamp,${escapeCSV(config.metadata.timestamp)}`)
    }
    if (config.metadata.timeframe) {
      csvLines.push(`Timeframe,${escapeCSV(config.metadata.timeframe)}`)
    }
    if (config.metadata.mode) {
      csvLines.push(`Mode,${escapeCSV(config.metadata.mode)}`)
    }
    if (config.metadata.scope) {
      csvLines.push(`Scope,${escapeCSV(config.metadata.scope)}`)
    }
    if (config.metadata.selectedAccounts && config.metadata.selectedAccounts.length > 0) {
      csvLines.push(`Selected Accounts,${config.metadata.selectedAccountsCount || config.metadata.selectedAccounts.length}`)
    }
    csvLines.push('')
  }

  // Add headers
  const headerRow = headers.map(header => escapeCSV(header)).join(',')
  csvLines.push(headerRow)

  // Add data rows
  rows.forEach(row => {
    const formattedRow = row.map((cell, index) => {
      const column = sheet.columns?.[index]
      const formatted = formatCellValue(cell, column, sheet.formatting)
      return escapeCSV(formatted)
    })
    csvLines.push(formattedRow.join(','))
  })

  return csvLines.join('\n')
}

/**
 * Export data as CSV
 * If multiple sheets, creates a ZIP file with multiple CSVs
 */
export async function exportToCSV(
  config: DataExportConfig
): Promise<ExportResult> {
  try {
    const delimiter = config.options?.csv?.delimiter || ','
    const encoding = config.options?.csv?.encoding || 'utf-8'
    const includeHeaders = config.options?.csv?.includeHeaders !== false
    const multiFileZip = config.options?.csv?.multiFileZip && config.sheets.length > 1

    // Single sheet export
    if (config.sheets.length === 1 && !multiFileZip) {
      const sheet = config.sheets[0]
      const csvContent = generateCSVContent(sheet, config)

      const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' })
      const filename = generateFilename(
        config.options?.filename || config.title,
        'csv'
      )

      return {
        success: true,
        format: 'csv',
        filename,
        blob
      }
    }

    // Multiple sheets export as ZIP
    if (multiFileZip) {
      const zip = new JSZip()

      // Add each sheet as a separate CSV file
      config.sheets.forEach((sheet, index) => {
        const csvContent = generateCSVContent(sheet, config)
        const sheetFilename = `${sheet.name || `Sheet_${index + 1}`}.csv`
        zip.file(sheetFilename, csvContent)
      })

      // Add a README if metadata exists
      if (config.metadata) {
        const readme: string[] = []
        readme.push(`# ${config.title}`)
        if (config.subtitle) {
          readme.push(`${config.subtitle}`)
        }
        readme.push('')
        readme.push('## Export Information')
        if (config.metadata.generatedBy) {
          readme.push(`Generated By: ${config.metadata.generatedBy}`)
        }
        if (config.metadata.timestamp) {
          readme.push(`Timestamp: ${config.metadata.timestamp}`)
        }
        if (config.metadata.timeframe) {
          readme.push(`Timeframe: ${config.metadata.timeframe}`)
        }
        if (config.metadata.mode) {
          readme.push(`Mode: ${config.metadata.mode}`)
        }
        readme.push('')
        readme.push('## Files Included')
        config.sheets.forEach((sheet, index) => {
          readme.push(`- ${sheet.name || `Sheet_${index + 1}`}.csv${sheet.description ? ` - ${sheet.description}` : ''}`)
        })

        zip.file('README.txt', readme.join('\n'))
      }

      // Generate ZIP blob
      const zipBlob = await zip.generateAsync({ type: 'blob' })
      const filename = generateFilename(
        config.options?.filename || config.title,
        'zip'
      )

      return {
        success: true,
        format: 'csv',
        filename,
        blob: zipBlob
      }
    }

    // Fallback: concatenate all sheets into a single CSV with separators
    const allContent: string[] = []

    allContent.push(`# ${config.title}`)
    if (config.subtitle) {
      allContent.push(`# ${config.subtitle}`)
    }
    allContent.push('')

    config.sheets.forEach((sheet, index) => {
      if (index > 0) {
        allContent.push('')
        allContent.push('---')
        allContent.push('')
      }

      allContent.push(`# Sheet: ${sheet.name}`)
      allContent.push('')

      const csvContent = generateCSVContent(sheet, config)
      allContent.push(csvContent)
    })

    const blob = new Blob([allContent.join('\n')], { type: 'text/csv;charset=utf-8;' })
    const filename = generateFilename(
      config.options?.filename || config.title,
      'csv'
    )

    return {
      success: true,
      format: 'csv',
      filename,
      blob
    }

  } catch (error) {
    console.error('CSV export failed:', error)
    return {
      success: false,
      format: 'csv',
      filename: '',
      error: error instanceof Error ? error.message : 'Unknown error during CSV export'
    }
  }
}

/**
 * Download CSV file
 */
export function downloadCSV(result: ExportResult): void {
  if (!result.success || !result.blob) {
    console.error('Cannot download CSV:', result.error)
    return
  }

  downloadBlob(result.blob, result.filename)
}
